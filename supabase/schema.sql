-- 비밀번호 해시/검증은 pgcrypto에서 처리합니다. Netlify 서버에는 bcrypt/WebSocket 의존성이 없습니다.
create or replace function public.initialize_admin(p_password text)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
begin
  if p_password is null or length(p_password)=0 then raise exception 'INITIAL_ADMIN_PASSWORD_REQUIRED'; end if;
  if exists(select 1 from public.app_settings where key='admin_password') then
    return jsonb_build_object('created',false);
  end if;
  insert into public.app_settings(key,value) values('admin_password',crypt(p_password,gen_salt('bf',11)));
  return jsonb_build_object('created',true);
end $$;

create or replace function public.verify_admin_password(p_password text)
returns jsonb
language sql
security definer
set search_path=public
as $$
  select jsonb_build_object('matched',coalesce((select crypt(p_password,value)=value from public.app_settings where key='admin_password'),false))
$$;

create or replace function public.set_admin_password(p_password text)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
begin
  if p_password is null or length(p_password)<4 then raise exception 'PASSWORD_TOO_SHORT'; end if;
  insert into public.app_settings(key,value,updated_at)
  values('admin_password',crypt(p_password,gen_salt('bf',11)),now())
  on conflict(key) do update set value=excluded.value,updated_at=now();
  return jsonb_build_object('ok',true);
end $$;

create or replace function public.authenticate_participant(p_employee_no text,p_password text)
returns table(id uuid,employee_no text,name text,credits integer,total_used integer)
language sql
security definer
set search_path=public
as $$
  select p.id,p.employee_no,p.name,p.credits,p.total_used
  from public.participants p
  where p.employee_no=p_employee_no
    and p.password_hash is not null
    and crypt(p_password,p.password_hash)=p.password_hash
  limit 1
$$;

create or replace function public.bulk_upsert_participants(p_rows jsonb)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  item jsonb;
  v_id uuid;
  v_employee_no text;
  v_name text;
  v_password text;
  v_credits integer;
  v_created integer:=0;
begin
  if jsonb_typeof(p_rows)<>'array' then raise exception 'ROWS_MUST_BE_ARRAY'; end if;
  for item in select value from jsonb_array_elements(p_rows)
  loop
    v_employee_no:=btrim(coalesce(item->>'employeeNo',''));
    v_name:=btrim(coalesce(item->>'name',''));
    v_password:=coalesce(item->>'password','');
    v_credits:=coalesce((item->>'credits')::integer,0);
    if v_employee_no='' or v_name='' or length(v_password)<4 or v_credits<0 then raise exception 'INVALID_PARTICIPANT_ROW'; end if;
    if exists(select 1 from public.participants where employee_no=v_employee_no) then continue; end if;
    insert into public.participants(employee_no,name,password_hash,credits,total_used)
    values(v_employee_no,v_name,crypt(v_password,gen_salt('bf',10)),v_credits,0)
    returning id into v_id;
    if v_credits>0 then
      insert into public.transactions(participant_id,amount,kind,description) values(v_id,v_credits,'initial','초기 크레딧');
    end if;
    v_created:=v_created+1;
  end loop;
  return jsonb_build_object('created',v_created);
end $$;

-- 한 번만 실행되는 결제. QR 재스캔이나 네트워크 재시도에 의한 중복 차감을 막습니다.
create or replace function public.pay_credit_once(
  p_participant_id uuid,
  p_amount integer,
  p_description text,
  p_nonce text
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_balance integer;
begin
  if p_amount is null or p_amount <= 0 then raise exception 'INVALID_AMOUNT'; end if;
  if exists(select 1 from public.transactions where qr_nonce = p_nonce) then
    select credits into v_balance from public.participants where id = p_participant_id;
    return jsonb_build_object('ok',true,'duplicate',true,'credits',v_balance);
  end if;
  select credits into v_balance from public.participants where id = p_participant_id for update;
  if not found then raise exception 'PARTICIPANT_NOT_FOUND'; end if;
  if v_balance < p_amount then raise exception 'INSUFFICIENT_CREDIT'; end if;
  update public.participants set credits = credits - p_amount, total_used = coalesce(total_used,0) + p_amount where id = p_participant_id;
  insert into public.transactions(participant_id,amount,kind,description,qr_nonce)
  values(p_participant_id,-p_amount,'payment',coalesce(nullif(p_description,''),'크레딧 결제'),p_nonce);
  return jsonb_build_object('ok',true,'credits',v_balance-p_amount);
end $$;

-- 이전 버전과의 호환을 위한 3개 인자 결제 함수.
create or replace function public.pay_credit(p_participant_id uuid,p_amount integer,p_description text)
returns jsonb language sql security definer set search_path=public
as $$ select public.pay_credit_once(p_participant_id,p_amount,p_description,gen_random_uuid()::text) $$;

create or replace function public.add_credit(p_participant_id uuid,p_amount integer,p_description text)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare v_balance integer;
begin
  if p_amount is null or p_amount <= 0 then raise exception 'INVALID_AMOUNT'; end if;
  update public.participants set credits=credits+p_amount where id=p_participant_id returning credits into v_balance;
  if not found then raise exception 'PARTICIPANT_NOT_FOUND'; end if;
  insert into public.transactions(participant_id,amount,kind,description) values(p_participant_id,p_amount,'credit',coalesce(nullif(p_description,''),'크레딧 지급'));
  return jsonb_build_object('ok',true,'credits',v_balance);
end $$;

create or replace function public.complete_game(p_participant_id uuid,p_game_code text)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  v_reward integer;
  v_name text;
  v_inserted integer;
  v_balance integer;
begin
  select reward,name into v_reward,v_name from public.games where code=p_game_code and active=true;
  if not found then raise exception 'GAME_NOT_FOUND'; end if;
  insert into public.game_completions(participant_id,game_code,reward)
  values(p_participant_id,p_game_code,v_reward)
  on conflict(participant_id,game_code) do nothing;
  get diagnostics v_inserted = row_count;
  if v_inserted = 0 then
    select credits into v_balance from public.participants where id=p_participant_id;
    return jsonb_build_object('ok',true,'already_completed',true,'reward',0,'credits',v_balance);
  end if;
  update public.participants set credits=credits+v_reward where id=p_participant_id returning credits into v_balance;
  insert into public.transactions(participant_id,amount,kind,description)
  values(p_participant_id,v_reward,'game',v_name||' 완료');
  return jsonb_build_object('ok',true,'already_completed',false,'reward',v_reward,'credits',v_balance);
end $$;

