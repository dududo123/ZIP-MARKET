-- 흔히 사용된 구버전 열 이름이 있으면 표준 열로 값을 복사합니다.
do $$
begin
  if exists(select 1 from information_schema.columns where table_schema='public' and table_name='participants' and column_name='employee_number') then
    execute 'update public.participants set employee_no = employee_number::text where employee_no is null';
  end if;
  if exists(select 1 from information_schema.columns where table_schema='public' and table_name='participants' and column_name='employee_id') then
    execute 'update public.participants set employee_no = employee_id::text where employee_no is null';
  end if;
  if exists(select 1 from information_schema.columns where table_schema='public' and table_name='participants' and column_name='balance') then
    execute 'update public.participants set credits = coalesce(balance::integer,0) where credits = 0';
  end if;
  if exists(select 1 from information_schema.columns where table_schema='public' and table_name='participants' and column_name='spent') then
    execute 'update public.participants set total_used = coalesce(spent::integer,0) where total_used = 0';
  end if;
  if exists(select 1 from information_schema.columns where table_schema='public' and table_name='games' and column_name='id') then
    execute 'update public.games set code = ''game-'' || substr(md5(id::text),1,10) where code is null';
  end if;
  if exists(select 1 from information_schema.columns where table_schema='public' and table_name='games' and column_name='title') then
    execute 'update public.games set name = title::text where name is null';
  end if;
end $$;

